//! Generate frontend TypeScript declarations from the owning Rust types.
use aidget::{
    community::model::*,
    runtime::ui::LocalWidgetDetails,
    widgets::{
        model::{WidgetDragMode, WidgetPermission},
        package::*,
    },
};
use clap::Parser;
use std::{fs, path::PathBuf};
use ts_rs::{Config, TS};
/// Generate or check the frontend declarations exported by Rust.
#[derive(Parser)]
struct Args {
    /// Compare generated content without writing files.
    #[arg(long)]
    check: bool,
}
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let cfg = Config::default().with_large_int("number");
    let types = [
        WidgetPermission::decl(&cfg),
        WidgetDragMode::decl(&cfg),
        WidgetPlatform::decl(&cfg),
        WidgetSize::decl(&cfg),
        WidgetConfig::decl(&cfg),
        PackageAuthor::decl(&cfg),
        PackageRepository::decl(&cfg),
        PackageManifest::decl(&cfg),
        FileDigest::decl(&cfg),
        RegistryEntry::decl(&cfg),
        Registry::decl(&cfg),
        CommunityEntry::decl(&cfg),
        CommunitySnapshot::decl(&cfg),
        DownloadCount::decl(&cfg),
        LocalWidgetDetails::decl(&cfg),
    ];
    let ts = format!(
        "// Generated by pnpm typegen. Do not edit.\n{}\n",
        types
            .iter()
            .map(|t| format!("export {t}"))
            .collect::<Vec<_>>()
            .join("\n")
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
    );
    let path = root.join("ui/src/types/rust.ts");
    if args.check {
        if fs::read_to_string(&path)? != ts {
            return Err(format!("{} is stale; run pnpm typegen", path.display()).into());
        }
    } else {
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, ts)?;
    }
    Ok(())
}
